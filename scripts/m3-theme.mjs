#!/usr/bin/env node
// Generates the Material 3 color scheme of the admin console from one seed color and
// writes it to src/m3-tokens.css as oklch values, for light (:root) and dark (html.dark).
//
//   node scripts/m3-theme.mjs            uses the seed below
//   node scripts/m3-theme.mjs '#455bd5'  uses another seed
//
// SchemeFidelity keeps the primary color close to the seed, so the brand blue stays recognizable.

import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  Hct,
  MaterialDynamicColors as roles,
  SchemeFidelity,
  argbFromHex,
} from '@material/material-color-utilities'

const SEED = process.argv[2] ?? '#455bd5'
const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/m3-tokens.css')

// sRGB -> OKLab -> OKLCH, https://bottosson.github.io/posts/oklab/
function oklch(argb, alpha = 1) {
  const lin = (c) => {
    c /= 255
    return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
  }
  const r = lin((argb >> 16) & 255)
  const g = lin((argb >> 8) & 255)
  const b = lin(argb & 255)
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b)
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b)
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b)
  const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s
  const A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s
  const B = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s
  const C = Math.hypot(A, B)
  const H = C < 0.0001 ? 0 : ((Math.atan2(B, A) * 180) / Math.PI + 360) % 360
  const a = alpha < 1 ? ` / ${Math.round(alpha * 100)}%` : ''
  return `oklch(${(L * 100).toFixed(1)}% ${C.toFixed(3)} ${H.toFixed(1)}${a})`
}

// Material 3 roles, named as CSS variables.
const ROLE_VARS = {
  'm3-primary': 'primary',
  'm3-on-primary': 'onPrimary',
  'm3-primary-container': 'primaryContainer',
  'm3-on-primary-container': 'onPrimaryContainer',
  'm3-secondary': 'secondary',
  'm3-on-secondary': 'onSecondary',
  'm3-secondary-container': 'secondaryContainer',
  'm3-on-secondary-container': 'onSecondaryContainer',
  'm3-tertiary': 'tertiary',
  'm3-on-tertiary': 'onTertiary',
  'm3-tertiary-container': 'tertiaryContainer',
  'm3-on-tertiary-container': 'onTertiaryContainer',
  'm3-error': 'error',
  'm3-on-error': 'onError',
  'm3-error-container': 'errorContainer',
  'm3-on-error-container': 'onErrorContainer',
  'm3-surface': 'surface',
  'm3-on-surface': 'onSurface',
  'm3-on-surface-variant': 'onSurfaceVariant',
  'm3-surface-container-lowest': 'surfaceContainerLowest',
  'm3-surface-container-low': 'surfaceContainerLow',
  'm3-surface-container': 'surfaceContainer',
  'm3-surface-container-high': 'surfaceContainerHigh',
  'm3-surface-container-highest': 'surfaceContainerHighest',
  'm3-outline': 'outline',
  'm3-outline-variant': 'outlineVariant',
  'm3-inverse-surface': 'inverseSurface',
  'm3-inverse-on-surface': 'inverseOnSurface',
  'm3-inverse-primary': 'inversePrimary',
  'm3-scrim': 'scrim',
}

function block(selector, dark) {
  const seed = Hct.fromInt(argbFromHex(SEED))
  const scheme = new SchemeFidelity(seed, dark, 0)
  const lines = Object.entries(ROLE_VARS).map(
    ([name, role]) => `  --${name}: ${oklch(roles[role].getArgb(scheme))};`
  )
  // Hover state layer: on-surface at 8% over surface.
  lines.push(`  --m3-hover: ${oklch(roles.onSurface.getArgb(scheme), 0.08)};`)
  // Chart colors: five hues around the seed, at a tone that reads on the surface.
  for (let i = 0; i < 5; i++) {
    const hue = (seed.hue + i * 72) % 360
    lines.push(`  --chart-${i + 1}: ${oklch(Hct.from(hue, 48, dark ? 72 : 50).toInt())};`)
  }
  return `${selector} {\n${lines.join('\n')}\n}`
}

